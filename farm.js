    function exposeControl(name, fn) {

        try {
            window[name] = fn;
        } catch (e) {}

        try {
            if (window.parent) {
                window.parent[name] = fn;
            }
        } catch (e) {}

        try {
            if (window.top) {
                window.top[name] = fn;
            }
        } catch (e) {}

        try {
            if (window.main) {
                window.main[name] = fn;
            }
        } catch (e) {}

        try {
            if (
                window.top &&
                window.top.main
            ) {
                window.top.main[name] = fn;
            }
        } catch (e) {}
    }


